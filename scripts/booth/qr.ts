/**
 * QR codes, encoded locally with qrcode-generator (MIT; a dev dependency, nothing is bundled), for the
 * legal pages in kiosk mode, which the app shows from the generated module `src/ui/shell/legalQr.ts`.
 *
 *   npm run qr        rewrites src/ui/shell/legalQr.ts from LEGAL_PAGES in src/ui/shell/legal.ts
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { format, resolveConfig } from 'prettier'
import qrcode from 'qrcode-generator'
import { LEGAL_PAGES } from '../../src/ui/shell/legal'

export const LEGAL_QR_FILE = new URL('../../src/ui/shell/legalQr.ts', import.meta.url)

/** Dark modules of the QR code for `text`, row by row (error correction M: 15 % may be damaged). */
export function qrMatrix(text: string, level: 'L' | 'M' | 'Q' | 'H' = 'M'): boolean[][] {
  const code = qrcode(0, level)
  code.addData(text, 'Byte')
  code.make()
  const n = code.getModuleCount()
  return Array.from({ length: n }, (_, r) => Array.from({ length: n }, (_, c) => code.isDark(r, c)))
}

/** The dark modules as one SVG path in module units (a rectangle per run of dark modules in a row). */
export function qrPath(matrix: boolean[][]): string {
  const parts: string[] = []
  matrix.forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      if (!row[x]) {
        x++
        continue
      }
      let run = 1
      while (row[x + run]) run++
      parts.push(`M${x} ${y}h${run}v1h-${run}z`)
      x += run
    }
  })
  return parts.join('')
}

/** The source of `legalQr.ts`, formatted as Prettier wants it. */
export async function legalQrModule(): Promise<string> {
  const entries = LEGAL_PAGES.map(({ url }) => {
    const matrix = qrMatrix(url)
    return `  '${url}': { size: ${matrix.length}, path: '${qrPath(matrix)}' },`
  })
  const source = [
    '// Generated by `npm run qr` (scripts/booth/qr.ts) from LEGAL_PAGES in legal.ts; do not edit.',
    '// QR codes of the legal pages for kiosk mode: dark modules as an SVG path, `size` modules square.',
    'export const LEGAL_QR: Record<string, { size: number; path: string }> = {',
    ...entries,
    '}',
    '',
  ].join('\n')
  const file = fileURLToPath(LEGAL_QR_FILE)
  return format(source, { ...(await resolveConfig(file)), filepath: file })
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(LEGAL_QR_FILE, await legalQrModule())
  console.log(`wrote ${LEGAL_QR_FILE.pathname}`)
}
